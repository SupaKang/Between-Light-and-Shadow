inline void draw_char(std::uint32_t* buf, int buf_w, int buf_h, char c, int ox, int oy, int scale, std::uint32_t color) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    if (c < 32 || c > 95) return;
    const std::uint8_t* rows = glyphs[c - 32];
    for (int y = 0; y < 7; ++y) {
        std::uint8_t row = rows[y];
        for (int x = 0; x < 5; ++x) {
            if ((row >> (4 - x)) & 1) {
                for (int py = 0; py < scale; ++py) {
                    for (int px = 0; px < scale; ++px) {
                        int dx = ox + x * scale + px;
                        int dy = oy + y * scale + py;
                        if (dx >= 0 && dx < buf_w && dy >= 0 && dy < buf_h) {
                            buf[dy * buf_w + dx] = color;
                        }
                    }
                }
            }
        }
    }
}

inline void draw_text(std::uint32_t* buf, int buf_w, int buf_h, const char* str, int x, int y, int scale, std::uint32_t color = 0xFFE8D8A0u) {
    for (; *str; ++str, x += 6 * scale) {
        draw_char(buf, buf_w, buf_h, *str, x, y, scale, color);
    }
}


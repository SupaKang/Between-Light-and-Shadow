-- Prologue: the old monk's tale of the 천지음양부, then waking in the jumak.

function prologue()
  local heard = ask("노승",
    "……어서 오게. 밤길이 차지. 등불 곁으로 앉게나.",
    "옛날 옛적, 하늘과 땅의 기운이 아직 제 길을 찾지 못하던 때의 일이오.",
    "산천의 영맥이 뒤엉켜, 백팔 가지 요괴가 밤낮을 가리지 않고 날뛰었지.",
    "자네, 혹시 이 이야기를 들어 본 적 있는가?",
    {"들어 보았습니다", "처음 듣습니다"})
  local where = ask("노승",
    heard == 1 and "허허, 그렇다면 끝까지 들어 보게. 사람들이 잊은 대목이 있으니."
                or "그렇겠지. 요즘 사람들은 이런 옛이야기를 잘 하지 않으니.",
    "그때 이름 없는 음양사 하나가 나타났소. 그는 요괴를 베지 않고, 하나하나 달래어 약조를 맺었다오.",
    "백팔 요괴와 맺은 약조를 한 장의 부적에 새기니, 그것이 천지음양부(天地陰陽符)라.",
    "부적이 영맥을 붙들자 세상은 낮과 밤을 되찾았고, 관상감이 대대로 그것을 지켜왔지.",
    "……허나 요즘 그 부적이 찢어졌다는 소문이 돌더이다. 그래, 자네는 어디로 가는 길인가?",
    {"도선사로 갑니다", "(말없이 고개를 숙인다)"})
  say("노승",
    where == 1 and "도선사라… 붉은 안개가 낀 곳이지. 등불을 꺼뜨리지 말게."
                or "말이 없는 이가 멀리 가는 법이지. 몸조심하게.",
    "자네가 이 이야기의 다음 장이 되겠구먼.")
  scene("placecard")
end

function wake()
  say("음양사",
    "(……꿈이었나. 등불 아래 노승이 옛이야기를 들려주던.)",
    "(벽사청의 명을 받아 도선사로 향하는 길이다. 오늘은 채비를 갖추고 길을 나서야 한다.)")
  toast("임무: 마을 어귀의 요괴를 퇴치하라")
end
